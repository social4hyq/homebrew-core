class Uv < Formula
  desc "Extremely fast Python package installer and resolver, written in Rust"
  homepage "https://docs.astral.sh/uv/"
  url "https://github.com/astral-sh/uv/archive/refs/tags/0.12.3.tar.gz"
  sha256 "7d95d35a941135b96cc344c63b8da427d456900f58621481b909eac00904db7f"
  license any_of: ["Apache-2.0", "MIT"]
  revision 2
  head "https://github.com/astral-sh/uv.git", branch: "main"

  livecheck do
    url :stable
    strategy :github_latest
  end

  bottle do
    root_url "https://atomgit.com/social4hyq/homebrew-core/releases/download/uv-v0.12.3-r3"
    sha256 cellar: :any_skip_relocation, arm64_ohos: "ad23eed372436697fb955410f5eb2f16a210cfd31b4379bfc83c99cbbdb905eb"
  end

  depends_on "cmake" => :build
  depends_on "ohos-sdk" => :build
  depends_on "pkgconf" => :build
  depends_on "rust" => :build
  # uv python install fetches unsigned ELFs that won't run under the app
  # sandbox (see caveats), so a brew-installed Python is the realistic way
  # to use uv here -- not just a build-time or test-only dependency.
  depends_on "python@3.14"

  # Both patches work around the same root cause: sandboxed processes can't
  # execve() the dynamic linker to parse its "Version X.Y" banner, which is
  # how upstream detects musl. 0001 fixes uv's own musl-version probe used
  # for wheel-tag resolution (mirrors the same fix Harmonybrew's python@3.14
  # already ships in pip's vendored copy of this file); 0002 fixes the
  # equivalent Rust-side probe used for interpreter discovery.
  patch do
    file "Patches/uv/0001-ohos-musllinux-skip-ld-exec.patch"
  end
  patch do
    file "Patches/uv/0002-ohos-libc-detect-skip-ld-exec.patch"
  end
  patch do
    file "Patches/uv/0003-ohos-autosign-wheels.patch"
  end

  def install
    # aws-lc-sys (via rustls/reqwest) needs its CMake+ohos.toolchain.cmake
    # path on this target; keg root, build.rs appends native/ itself.
    ENV["OHOS_NDK_HOME"] = formula_opt_prefix("ohos-sdk")

    # --no-default-features: drops jemalloc, unbuildable on this target and
    # not needed.
    system "cargo", "install", "--no-default-features", *std_cargo_args(path: "crates/uv")

    generate_completions_from_executable(bin/"uv", "generate-shell-completion")
    generate_completions_from_executable(bin/"uvx", "--generate-shell-completion")
  end

  def caveats
    <<~CAVEATS
      Wheel .so files are now auto-signed on install (patch 0003), so binary
      wheels import out of the box for uv pip/add/sync and uvx.

      uv python install still fetches unsigned standalone interpreter builds
      whose own lib-dynload .so are NOT installed through the wheel path and
      so are NOT auto-signed -- use `brew install python@3.14` instead.
    CAVEATS
  end

  test do
    (testpath/"requirements.in").write <<~REQUIREMENTS
      requests
    REQUIREMENTS

    compiled = shell_output("#{bin}/uv pip compile -q requirements.in")
    assert_match "This file was autogenerated by uv", compiled
    assert_match "# via requests", compiled

    system bin/"uv", "venv", "--python", formula_opt_bin("python@3.14")/"python3.14", "test-venv"
    system bin/"uv", "pip", "install", "--python", "test-venv/bin/python", "requests"
    py = testpath/"test-venv/bin/python"
    assert_match "requests", shell_output("#{py} -c \"import requests; print('requests', requests.__version__)\"")
  end
end
